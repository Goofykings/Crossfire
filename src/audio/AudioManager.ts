import { assetUrl } from '../core/assets';

export type SoundName =
  | 'shot'
  | 'empty'
  | 'reload_out'
  | 'reload_in'
  | 'hit'
  | 'hit_crit'
  | 'target_down'
  | 'blocked'
  | 'step1'
  | 'step2'
  | 'step3'
  | 'step4'
  | 'land'
  | 'jump'
  | 'ui_click'
  | 'ui_hover'
  | 'zone_enter';

const FILES: Record<SoundName, string> = {
  shot: 'blaster_shot.wav',
  empty: 'empty_click.wav',
  reload_out: 'reload_out.wav',
  reload_in: 'reload_in.wav',
  hit: 'hit_marker.wav',
  hit_crit: 'hit_crit.wav',
  target_down: 'target_down.wav',
  blocked: 'blocked.wav',
  step1: 'step_1.wav',
  step2: 'step_2.wav',
  step3: 'step_3.wav',
  step4: 'step_4.wav',
  land: 'land.wav',
  jump: 'jump.wav',
  ui_click: 'ui_click.wav',
  ui_hover: 'ui_hover.wav',
  zone_enter: 'zone_enter.wav',
};

/**
 * Small Web Audio wrapper. The context is created lazily on the first user gesture (browser
 * autoplay policy); all sounds are short WAV files generated by tools/make_audio.py.
 */
export class AudioManager {
  private ctx: AudioContext | null = null;
  private master: GainNode | null = null;
  private readonly buffers = new Map<SoundName, AudioBuffer>();
  private volume = 0.7;

  /** Current master volume (0..1). */
  get masterVolume(): number {
    return this.volume;
  }
  private loading: Promise<void> | null = null;

  /** Must be called from a user gesture handler (click/keydown). */
  unlock(): void {
    if (!this.ctx) {
      try {
        this.ctx = new AudioContext();
        this.master = this.ctx.createGain();
        this.master.gain.value = this.volume;
        this.master.connect(this.ctx.destination);
        this.loading = this.loadAll();
      } catch {
        this.ctx = null;
        return;
      }
    }
    if (this.ctx.state === 'suspended') void this.ctx.resume();
  }

  setVolume(v: number): void {
    this.volume = v;
    if (this.master) this.master.gain.value = v;
  }

  private async loadAll(): Promise<void> {
    const ctx = this.ctx!;
    await Promise.all(
      (Object.keys(FILES) as SoundName[]).map(async (name) => {
        try {
          const res = await fetch(assetUrl(`assets/audio/${FILES[name]}`));
          if (!res.ok) return;
          const buf = await ctx.decodeAudioData(await res.arrayBuffer());
          this.buffers.set(name, buf);
        } catch {
          /* a missing sound must never break the game */
        }
      }),
    );
  }

  get ready(): Promise<void> {
    return this.loading ?? Promise.resolve();
  }

  play(name: SoundName, opts: { volume?: number; rate?: number; pan?: number; jitter?: number } = {}): void {
    const ctx = this.ctx;
    const buf = this.buffers.get(name);
    if (!ctx || !this.master || !buf) return;
    const src = ctx.createBufferSource();
    src.buffer = buf;
    const jitter = opts.jitter ?? 0.04;
    src.playbackRate.value = (opts.rate ?? 1) * (1 + (Math.random() * 2 - 1) * jitter);
    const gain = ctx.createGain();
    gain.gain.value = opts.volume ?? 1;
    let node: AudioNode = gain;
    if (opts.pan !== undefined && ctx.createStereoPanner) {
      const p = ctx.createStereoPanner();
      p.pan.value = Math.max(-1, Math.min(1, opts.pan));
      gain.connect(p);
      node = p;
    }
    src.connect(gain);
    node.connect(this.master);
    src.start();
  }
}
